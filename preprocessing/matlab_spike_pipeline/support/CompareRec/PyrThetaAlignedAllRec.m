function thetaAlignedMeanStat = accumMeanStat(thetaAlignedMean,timeStepRun)

    %% baseline
    indThetaBaseline = find(timeStepRun >= -3 & timeStepRun < -2);
    thetaAlignedMeanStat.indThetaBaseline = indThetaBaseline;
    thetaAlignedMeanStat.meanThetaFreqNonStimGoodPerRecFieldBaseline = [...
        mean(mean(thetaAlignedMean.meanThetaFreqNonStimGoodPerRecField(:,indThetaBaseline))),...
        mean(mean(thetaAlignedMean.meanThetaFreqNonStimGoodPerRecNoField(:,indThetaBaseline)))];
    thetaAlignedMeanStat.meanThetaAmpNonStimGoodPerRecFieldBaseline = [...
        mean(mean(thetaAlignedMean.meanThetaAmpNonStimGoodPerRecField(:,indThetaBaseline))),...
        mean(mean(thetaAlignedMean.meanThetaAmpNonStimGoodPerRecNoField(:,indThetaBaseline)))];
    
    thetaAlignedMeanStat.meanThetaFreqNonStimBadPerRecFieldBaseline = [...
        mean(mean(thetaAlignedMean.meanThetaFreqNonStimBadPerRecField(:,indThetaBaseline))),...
        mean(mean(thetaAlignedMean.meanThetaFreqNonStimBadPerRecNoField(:,indThetaBaseline)))];
    thetaAlignedMeanStat.meanThetaAmpNonStimBadPerRecFieldBaseline = [...
        mean(mean(thetaAlignedMean.meanThetaAmpNonStimBadPerRecField(:,indThetaBaseline))),...
        mean(mean(thetaAlignedMean.meanThetaAmpNonStimBadPerRecNoField(:,indThetaBaseline)))];
    
    thetaAlignedMeanStat.meanThetaFreqStimPerRecFieldBaseline = [...
        mean(mean(thetaAlignedMean.meanThetaFreqStimPerRecField(:,indThetaBaseline))),...
        mean(mean(thetaAlignedMean.meanThetaFreqStimPerRecNoField(:,indThetaBaseline)))];
    thetaAlignedMeanStat.meanThetaAmpStimPerRecFieldBaseline = [...
        mean(mean(thetaAlignedMean.meanThetaAmpStimPerRecField(:,indThetaBaseline))),...
        mean(mean(thetaAlignedMean.meanThetaAmpStimPerRecNoField(:,indThetaBaseline)))];
    
    thetaAlignedMeanStat.pRSMeanThetaFreqNonStimGoodPerRecFieldBaseline = ...
        ranksum(reshape(thetaAlignedMean.meanThetaFreqNonStimGoodPerRecField(:,indThetaBaseline),[],1),...
        reshape(thetaAlignedMean.meanThetaFreqNonStimGoodPerRecNoField(:,indThetaBaseline),[],1));
