function thetaAligned = accumTheta(paths,filenames,mazeSess,task,behAligned)
  
    numRec = size(paths,1);
    thetaAligned = struct('task',[],... % no cue - 1, AL - 2, PL - 3
                    'indRec',[],... % recording index
                    'indRecNonStimBad',behAligned.indRecNonStimBad,... % recording index for all the reoordings with non-stimulated bad trials
                    'indRecStim',behAligned.indRecStim,... % recording index for all the reoordings with stimulated trials
                    'timeStepRun',[],...
                    ...
                    'meanThetaFreqNonStimGoodPerRec',[],... % mean ThetaFreq trace per recording (non-stimulated good trials)
                    'meanThetaFreqNonStimGoodFiltPerRec',[],... % filtered mean ThetaFreq trace per recording (non-stimulated good trials)
                    'stdThetaFreqNonStimGoodPerRec',[],... % mean ThetaFreq trace per recording (non-stimulated good trials)
                    'meanThetaFreqNonStimBadPerRec',[],... % mean ThetaFreq trace per recording (non-stimulated bad trials)
                    'meanThetaFreqNonStimBadFiltPerRec',[],... % filtered mean ThetaFreq trace per recording (non-stimulated bad trials)
                    'stdThetaFreqNonStimBadPerRec',[],... % mean ThetaFreq trace per recording (non-stimulated bad trials)
                    'meanThetaFreqStimPerRec',[],... % mean ThetaFreq trace per recording (stimulated trials)
                    'meanThetaFreqStimFiltPerRec',[],... % filtered mean ThetaFreq trace per recording (stimulated trials)
                    'stdThetaFreqStimPerRec',[],... % mean ThetaFreq trace per recording (stimulated trials)
                    ...
                    'meanThetaAmpNonStimGoodPerRec',[],... % mean ThetaAmp trace per recording (non-stimulated good trials)
                    'stdThetaAmpNonStimGoodPerRec',[],... % mean ThetaAmp trace per recording (non-stimulated good trials)
                    'meanThetaAmpNonStimBadPerRec',[],... % mean ThetaFreq trace per recording (non-stimulated bad trials)
                    'stdThetaAmpNonStimBadPerRec',[],... % mean ThetaFreq trace per recording (non-stimulated bad trials)
                    'meanThetaAmpStimPerRec',[],... % mean ThetaFreq trace per recording (stimulated trials)
                    'stdThetaAmpStimPerRec',[]); % mean ThetaFreq trace per recording (stimulated trials)
     
    for i = 1:numRec
        if(task == 3 & i == 8)
            a = 1;
        end
        disp(filenames(i,:));            
        
        fullPath = [paths(i,:) filenames(i,:) '_ThetaAlignRun_msess' num2str(mazeSess(i)) '.mat']; 
        if(exist(fullPath) == 0)
            disp('_ThetaAlignRun.mat file does not exist.');
            return;
        end
        load(fullPath,'meanThetaNonStimGood','meanThetaNonStimBad',...
            'meanThetaStim','t');
        
        thetaAligned.task = [thetaAligned.task task];
        thetaAligned.indRec = [thetaAligned.indRec i];
        thetaAligned.timeStepRun = t;
        if(isempty(thetaAligned.meanThetaFreqNonStimGoodPerRec))
            thetaAligned.meanThetaFreqNonStimGoodPerRec = meanThetaNonStimGood.meanThetaFreqGoodTr;
            thetaAligned.meanThetaFreqNonStimGoodFiltPerRec = meanThetaNonStimGood.meanThetaFreqFiltGoodTr;
            thetaAligned.stdThetaFreqNonStimGoodPerRec = meanThetaNonStimGood.stdThetaFreqGoodTr;
                        
            thetaAligned.meanThetaAmpNonStimGoodPerRec = meanThetaNonStimGood.meanThetaAmpGoodTr;
            thetaAligned.stdThetaAmpNonStimGoodPerRec = meanThetaNonStimGood.stdThetaAmpGoodTr;
        else
            thetaAligned.meanThetaFreqNonStimGoodPerRec = ...
                [thetaAligned.meanThetaFreqNonStimGoodPerRec; meanThetaNonStimGood.meanThetaFreqGoodTr];
            thetaAligned.meanThetaFreqNonStimGoodFiltPerRec = ...
                [thetaAligned.meanThetaFreqNonStimGoodFiltPerRec; meanThetaNonStimGood.meanThetaFreqFiltGoodTr];
            thetaAligned.stdThetaFreqNonStimGoodPerRec = ...
                [thetaAligned.stdThetaFreqNonStimGoodPerRec; meanThetaNonStimGood.stdThetaFreqGoodTr];
            
            thetaAligned.meanThetaAmpNonStimGoodPerRec = ...
                [thetaAligned.meanThetaAmpNonStimGoodPerRec; meanThetaNonStimGood.meanThetaAmpGoodTr];
            thetaAligned.stdThetaAmpNonStimGoodPerRec = ...
                [thetaAligned.stdThetaAmpNonStimGoodPerRec; meanThetaNonStimGood.stdThetaAmpGoodTr];
                        
        end      
        
        if(sum(behAligned.indRecNonStimBad == i) > 0)
            if(isempty(thetaAligned.meanThetaFreqNonStimBadPerRec))
                thetaAligned.meanThetaFreqNonStimBadPerRec = meanThetaNonStimBad.meanThetaFreqGoodTr;
                thetaAligned.meanThetaFreqNonStimBadFiltPerRec = meanThetaNonStimBad.meanThetaFreqFiltGoodTr;
                thetaAligned.stdThetaFreqNonStimBadPerRec = meanThetaNonStimBad.stdThetaFreqGoodTr;

                thetaAligned.meanThetaAmpNonStimBadPerRec = meanThetaNonStimBad.meanThetaAmpGoodTr;
                thetaAligned.stdThetaAmpNonStimBadPerRec = meanThetaNonStimBad.stdThetaAmpGoodTr;
            else
                thetaAligned.meanThetaFreqNonStimBadPerRec = ...
                    [thetaAligned.meanThetaFreqNonStimBadPerRec; meanThetaNonStimBad.meanThetaFreqGoodTr];
                thetaAligned.meanThetaFreqNonStimBadFiltPerRec = ...
                    [thetaAligned.meanThetaFreqNonStimBadFiltPerRec; meanThetaNonStimBad.meanThetaFreqFiltGoodTr];
                thetaAligned.stdThetaFreqNonStimBadPerRec = ...
                    [thetaAligned.stdThetaFreqNonStimBadPerRec; meanThetaNonStimBad.stdThetaFreqGoodTr];

                thetaAligned.meanThetaAmpNonStimBadPerRec = ...
                    [thetaAligned.meanThetaAmpNonStimBadPerRec; meanThetaNonStimBad.meanThetaAmpGoodTr];
                thetaAligned.stdThetaAmpNonStimBadPerRec = ...
                    [thetaAligned.stdThetaAmpNonStimBadPerRec; meanThetaNonStimBad.stdThetaAmpGoodTr];
            end
        end
        
        if(sum(behAligned.indRecStim == i) > 0)
            if(isempty(thetaAligned.meanThetaFreqStimPerRec))
                thetaAligned.meanThetaFreqStimPerRec = meanThetaStim.meanThetaFreqGoodTr;
                thetaAligned.meanThetaFreqStimFiltPerRec = meanThetaStim.meanThetaFreqFiltGoodTr;
                thetaAligned.stdThetaFreqStimPerRec = meanThetaStim.stdThetaFreqGoodTr;
            
                thetaAligned.meanThetaAmpStimPerRec = meanThetaStim.meanThetaAmpGoodTr;
                thetaAligned.stdThetaAmpStimPerRec = meanThetaStim.stdThetaAmpGoodTr;
            else                
                thetaAligned.meanThetaFreqStimPerRec = ...
                    [thetaAligned.meanThetaFreqStimPerRec; meanThetaStim.meanThetaFreqGoodTr];
                thetaAligned.meanThetaFreqStimFiltPerRec = ...
                    [thetaAligned.meanThetaFreqStimFiltPerRec; meanThetaStim.meanThetaFreqFiltGoodTr];
                thetaAligned.stdThetaFreqStimPerRec = ...
                    [thetaAligned.stdThetaFreqStimPerRec; meanThetaStim.stdThetaFreqGoodTr];
            
                thetaAligned.meanThetaAmpStimPerRec = ...
                    [thetaAligned.meanThetaAmpStimPerRec; meanThetaStim.meanThetaAmpGoodTr];
                thetaAligned.stdThetaAmpStimPerRec = ...
                    [thetaAligned.stdThetaAmpStimPerRec; meanThetaStim.stdThetaAmpGoodTr];
            end
        end
    end        
end

